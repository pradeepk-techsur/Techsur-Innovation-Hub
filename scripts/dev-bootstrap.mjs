/**
 * Dev bootstrap — make `npm run dev` self-sufficient.
 *
 * The Pivota preview sandbox starts this app with `npm run dev` and nothing
 * else: no compose, no database. Without a bootstrap the app boots onto an
 * unreachable DATABASE_URL and every data-backed page 500s with ECONNREFUSED.
 *
 * This script runs before `next dev` and, in order:
 *   1. loads .env / .env.local into the environment (real env vars always win),
 *   2. makes sure Postgres is answering queries — starting the compose `db`
 *      service if it is not, and it can,
 *   3. applies migrations and the idempotent seeds.
 *
 * It lives here rather than in `.pivota/start-dev.sh` on purpose: that file is
 * regenerated by the platform, and the region it advertises as preserved sits
 * after the script's final `exit`, so it never runs.
 *
 * Every failure is non-fatal — it logs loudly and lets `next dev` start anyway,
 * so a database hiccup degrades the app instead of stranding the whole preview.
 */

import { existsSync, readFileSync } from 'node:fs';
import { createConnection } from 'node:net';
import { spawnSync } from 'node:child_process';

const TAG = '[dev-bootstrap]';
const log = (msg) => console.log(`${TAG} ${msg}`);
const warn = (msg) => console.warn(`${TAG} WARN ${msg}`);

/** Minimal .env parser — avoids a dependency and any Node-version floor. */
function loadEnvFile(file) {
  if (!existsSync(file)) return 0;
  let count = 0;
  for (const raw of readFileSync(file, 'utf8').split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    if (!key || key in process.env) continue; // real env and earlier files win
    let value = line.slice(eq + 1).trim();
    // Strip a trailing `# comment`, then matching surrounding quotes.
    if (!value.startsWith('"') && !value.startsWith("'")) {
      value = value.replace(/\s+#.*$/, '').trim();
    }
    if (value.length >= 2 && (value[0] === '"' || value[0] === "'") && value.at(-1) === value[0]) {
      value = value.slice(1, -1);
    }
    process.env[key] = value;
    count++;
  }
  return count;
}

/**
 * Readiness = Postgres ANSWERS A QUERY, not that the port is open.
 *
 * A freshly created postgres container binds 5432 while initdb is still
 * running, so a TCP connect succeeds seconds before the server can serve:
 * the first real statement comes back ECONNRESET and the migration dies on a
 * database that was about to be fine. Ask for `SELECT 1` instead.
 */
async function canQuery(connectionString, timeoutMs = 2000) {
  let pg;
  try {
    ({ default: pg } = await import('pg'));
  } catch {
    return null; // driver unavailable — caller falls back to a TCP probe
  }
  const client = new pg.Client({ connectionString, connectionTimeoutMillis: timeoutMs });
  try {
    await client.connect();
    await client.query('SELECT 1');
    return true;
  } catch {
    return false;
  } finally {
    try {
      await client.end();
    } catch {
      /* already broken; nothing to release */
    }
  }
}

/** Fallback only, for when `pg` is not installed yet. */
function tcpProbe(host, port, timeoutMs = 1500) {
  return new Promise((resolve) => {
    const socket = createConnection({ host, port });
    const done = (ok) => {
      socket.removeAllListeners();
      socket.destroy();
      resolve(ok);
    };
    socket.setTimeout(timeoutMs);
    socket.once('connect', () => done(true));
    socket.once('timeout', () => done(false));
    socket.once('error', () => done(false));
  });
}

async function isReady(connectionString, host, port) {
  const answered = await canQuery(connectionString);
  return answered === null ? tcpProbe(host, port) : answered;
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function waitUntilReady(connectionString, host, port, seconds) {
  for (let i = 0; i < seconds; i++) {
    if (await isReady(connectionString, host, port)) return true;
    await sleep(1000);
  }
  return false;
}

function run(command, args) {
  const shown = [command, ...args].join(' ');
  log(`running: ${shown}`);
  const result = spawnSync(command, args, { stdio: 'inherit', env: process.env });
  if (result.error) {
    warn(`${shown} could not start (${result.error.message})`);
    return false;
  }
  if (result.status !== 0) {
    warn(`${shown} exited ${result.status}`);
    return false;
  }
  return true;
}

/** `docker compose` exists AND its daemon answers. */
function composeAvailable() {
  const result = spawnSync('docker', ['compose', 'version'], { stdio: 'ignore' });
  return !result.error && result.status === 0;
}

function composeFile() {
  return ['docker-compose.yml', 'compose.yaml', 'compose.yml'].find((f) => existsSync(f));
}

async function main() {
  // .env.local overrides .env, matching Next's own precedence: load it first,
  // since loadEnvFile never overwrites a key that is already set.
  const loaded = loadEnvFile('.env.local') + loadEnvFile('.env');
  if (loaded > 0) log(`loaded ${loaded} variable(s) from .env.local / .env`);

  const target = process.env.DATABASE_ADMIN_URL ?? process.env.DATABASE_URL;
  if (!target) {
    warn('neither DATABASE_ADMIN_URL nor DATABASE_URL is set — skipping database bootstrap');
    return;
  }

  let url;
  try {
    url = new URL(target);
  } catch {
    warn('DATABASE_URL is not a parseable URL — skipping database bootstrap');
    return;
  }

  const host = url.hostname;
  const port = Number(url.port || 5432);
  const isLocal = ['localhost', '127.0.0.1', '::1', '0.0.0.0'].includes(host);

  if (await isReady(target, host, port)) {
    log(`postgres answering at ${host}:${port}`);
  } else if (!isLocal) {
    // Running under compose: the db service is a sibling container we do not
    // manage. Wait for it rather than trying to start anything.
    log(`waiting for postgres at ${host}:${port} (managed elsewhere)…`);
    if (!(await waitUntilReady(target, host, port, 60))) {
      warn(`postgres never answered at ${host}:${port} — starting the app anyway`);
      return;
    }
  } else {
    const file = composeFile();
    if (!file) {
      warn(`no postgres at ${host}:${port} and no compose file to start one — starting the app anyway`);
      return;
    }
    if (!composeAvailable()) {
      warn(`no postgres at ${host}:${port} and docker is unavailable — starting the app anyway`);
      return;
    }
    log(`no postgres at ${host}:${port}; starting the '${file}' db service`);
    if (!run('docker', ['compose', '-f', file, 'up', '-d', 'db'])) {
      warn('could not start the db service — starting the app anyway');
      return;
    }
    log('waiting for postgres to accept queries…');
    if (!(await waitUntilReady(target, host, port, 90))) {
      warn(`db container started but never answered on ${host}:${port} — starting the app anyway`);
      return;
    }
    log(`postgres answering at ${host}:${port}`);
  }

  // Guard: never auto-migrate/seed a production database from a dev command.
  if (process.env.NODE_ENV === 'production' && process.env.ALLOW_PROD_DB_BOOTSTRAP !== 'true') {
    warn('NODE_ENV=production — refusing to auto-migrate/seed (set ALLOW_PROD_DB_BOOTSTRAP=true to override)');
    return;
  }

  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  // Migrations first; the seeds are all idempotent, so a warm database re-runs
  // them as a fast no-op.
  if (!run(npm, ['run', 'db:migrate'])) {
    warn('migrations failed — data-backed pages will not work until this is fixed');
    return;
  }
  run(npm, ['run', 'db:seed']);
  run(npm, ['run', 'db:seed-launch']);
  log('database ready');
}

main().catch((err) => {
  warn(`unexpected error: ${err?.message ?? err}`);
  process.exit(0); // never block the dev server
});
